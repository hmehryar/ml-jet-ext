"""ML-JET-Ext precomputed M1--M5 aggregate dataset loader.

Dataset stays on CPU: transfer batches to the accelerator in the training loop.
The split files are generated by dataset_builder/11_generate_dataset_splits.py.
"""
from __future__ import annotations

from pathlib import Path
from typing import Optional, Sequence

import numpy as np
import pandas as pd
import torch
from torch.utils.data import DataLoader, Dataset

ALPHA_VALUES = np.array([0.20, 0.25, 0.30, 0.35, 0.40, 0.45, 0.50], dtype=np.float64)
Q0_VALUES = np.array([1.0, 1.5, 2.0, 2.5, 3.0], dtype=np.float64)
REQUIRED_COLUMNS = {"agg_file_path", "alpha", "q0", "config"}


def _class_index(value, options, name):
    matches = np.flatnonzero(np.isclose(float(value), options, rtol=0, atol=1e-6))
    if len(matches) != 1:
        raise ValueError(f"Unrecognized {name} value: {value!r}")
    return int(matches[0])


class MomentJetDataset(Dataset):
    """Read normalized [5,32,32] aggregate arrays and select moment channels.

    Returns (image, labels) where image is float32 [C,32,32] on CPU, and
    labels has 'alpha_output' and 'q0_output' as scalar LongTensors.
    """

    def __init__(self, csv_path, dataset_root, moments: Sequence[int] = (1, 2),
                 validate_files: bool = False, check_normalization: bool = False):
        self.csv_path = Path(csv_path)
        self.dataset_root = Path(dataset_root)
        self.moments = tuple(int(m) for m in moments)
        if not self.moments or len(set(self.moments)) != len(self.moments) or any(m not in range(1, 6) for m in self.moments):
            raise ValueError("moments must be a non-empty sequence of distinct integers from 1 to 5")
        self.channels = np.asarray([m - 1 for m in self.moments], dtype=np.intp)
        self.check_normalization = bool(check_normalization)
        if not self.csv_path.is_file():
            raise FileNotFoundError(f"Missing split CSV: {self.csv_path}")
        self.df = pd.read_csv(self.csv_path)
        missing = REQUIRED_COLUMNS - set(self.df.columns)
        if missing:
            raise ValueError(f"{self.csv_path}: missing columns {sorted(missing)}")
        if self.df.empty:
            raise ValueError(f"Empty split: {self.csv_path}")
        if self.df["agg_file_path"].isna().any() or self.df["agg_file_path"].duplicated().any():
            raise ValueError(f"Duplicate or missing agg_file_path values in {self.csv_path}")

        self.paths = []
        self.alpha_labels = []
        self.q0_labels = []
        for row in self.df.itertuples(index=False):
            rel = Path(str(row.agg_file_path))
            if rel.is_absolute() or ".." in rel.parts or not str(rel).strip():
                raise ValueError(f"Unsafe relative image path: {rel}")
            if rel.parts[0] != str(row.config):
                raise ValueError(f"Configuration/path mismatch for {rel}")
            path = self.dataset_root / rel
            if validate_files and not path.is_file():
                raise FileNotFoundError(f"Missing aggregate array: {path}")
            self.paths.append(path)
            self.alpha_labels.append(_class_index(row.alpha, ALPHA_VALUES, "alpha"))
            self.q0_labels.append(_class_index(row.q0, Q0_VALUES, "q0"))

    def __len__(self):
        return len(self.paths)

    def __getitem__(self, index):
        path = self.paths[index]
        arr = np.load(path, allow_pickle=False)
        if arr.shape != (5, 32, 32) or arr.dtype != np.float32:
            raise ValueError(f"{path}: expected float32 [5,32,32], got {arr.dtype} {arr.shape}")
        if not np.isfinite(arr).all():
            raise ValueError(f"{path}: nonfinite values")
        if self.check_normalization:
            lower = np.array([0, 0, -1, 0, -1], dtype=np.float32)
            upper = np.ones(5, dtype=np.float32)
            if np.any(arr.min(axis=(1, 2)) < lower - 1e-6) or np.any(arr.max(axis=(1, 2)) > upper + 1e-6):
                raise ValueError(f"{path}: moments outside expected normalized ranges")
        # np advanced indexing makes a copy. Ensure independent contiguous CPU memory.
        image = torch.from_numpy(np.ascontiguousarray(arr[self.channels]))
        labels = {
            "alpha_output": torch.tensor(self.alpha_labels[index], dtype=torch.long),
            "q0_output": torch.tensor(self.q0_labels[index], dtype=torch.long),
        }
        return image, labels


def get_moment_dataloaders(dataset_root, moments=(1, 2), batch_size=32,
                           num_workers=4, seed=42, fold: Optional[int] = None,
                           pin_memory=None, validate_files=False,
                           check_normalization=False):
    """Return train, validation, test loaders using precomputed, fixed CSV splits.

    fold=None: splits/train.csv and splits/val.csv.
    fold=0..4: splits/five_fold/fold_{fold}_{train,val}.csv.
    Test always uses splits/test.csv (never a CV validation fold).
    """
    root = Path(dataset_root)
    split_dir = root / "splits"
    if fold is None:
        train_csv, val_csv = split_dir / "train.csv", split_dir / "val.csv"
    else:
        if isinstance(fold, bool) or not isinstance(fold, int) or not 0 <= fold <= 4:
            raise ValueError("fold must be None or an integer from 0 to 4")
        train_csv = split_dir / "five_fold" / f"fold_{fold}_train.csv"
        val_csv = split_dir / "five_fold" / f"fold_{fold}_val.csv"
    test_csv = split_dir / "test.csv"
    datasets = [MomentJetDataset(csv, root, moments, validate_files, check_normalization)
                for csv in (train_csv, val_csv, test_csv)]
    train_paths, val_paths, test_paths = [set(str(p) for p in ds.paths) for ds in datasets]
    if train_paths & val_paths or train_paths & test_paths or val_paths & test_paths:
        raise ValueError("Aggregate file path leakage between train/val/test splits")
    if pin_memory is None:
        pin_memory = torch.cuda.is_available()
    generator = torch.Generator().manual_seed(int(seed))
    loaders = tuple(DataLoader(ds, batch_size=batch_size, shuffle=(i == 0),
                               num_workers=num_workers, pin_memory=pin_memory,
                               persistent_workers=num_workers > 0, generator=generator if i == 0 else None)
                    for i, ds in enumerate(datasets))
    return loaders
